/**
 * Live scoring domain model — Match.
 *
 * Sits at the top of Point → Game → Set → Match. `scoringSystem` is decided once
 * here and is meant to be threaded down unchanged through Set and Game, the same
 * way `trackedPlayerId`/`opponentId` are set once at Match and passed down through
 * every Point (see `point.ts`) — so no level below Match ever redecides the
 * match's format.
 */

// --- Supporting enums -------------------------------------------------------
//
// Same convention as point.ts: plain string-literal unions, each paired with a
// runtime array of its members for validating untrusted input.

// TODO: provisional — revisit once we know which surfaces coaches actually track.
// "unspecified" is a real, stored value here (not the absence of one — see
// `createMatch`'s default) for a coach who doesn't know or doesn't care.
// The backend has no equivalent member: `surface` is nullable instead, so
// the sync layer needs to translate "unspecified" to null on the way out.
export type SurfaceType = "hard" | "clay" | "grass" | "carpet" | "unspecified";
export const SURFACE_TYPES: readonly SurfaceType[] = [
  "hard",
  "clay",
  "grass",
  "carpet",
  "unspecified",
];

// The named format a coach picks at match setup. Started out as two separate
// concepts — this named preset (`ScoringSystem`) plus a `ScoringRules` bag of
// the concrete rule values it implies (ad scoring, tiebreak-at, ...) — but
// `ScoringRules` never grew any fields, so they were merged into just this
// enum. Whatever value lands here is fixed for the whole match — Match decides
// it once, Set and Game only ever read it, never redefine it (see module doc
// comment above).
export type ScoringSystem =
  | "traditional"
  | "mens_grand_slam"
  | "womens_grand_slam"
  | "no_ad_scoring"
  | "match_tiebreak_10_points"
  | "short_sets"
  | "pro_set"
  | "legacy";
export const SCORING_SYSTEMS: readonly ScoringSystem[] = [
  "traditional",
  "mens_grand_slam",
  "womens_grand_slam",
  "no_ad_scoring",
  "match_tiebreak_10_points",
  "short_sets",
  "pro_set",
  "legacy",
];

// A match can end other than by winning enough sets. All three produce a
// winner that matchStateFor's derivation (state.ts) can't — it works from
// MatchSet[] alone, and none of these three are visible there.
export type MatchEndReason = "retirement" | "walkover" | "default";
export const MATCH_END_REASONS: readonly MatchEndReason[] = ["retirement", "walkover", "default"];

export interface MatchOutcomeOverride {
  reason: MatchEndReason;
  // Must equal trackedPlayerId or opponentId — checked in Match.create.
  winner: string;
}

/**
 * `id` and `trackedPlayerId`/`opponentId` follow Point's convention: `trackedPlayerId`
 * always comes from a real `Player` row, `opponentId` does too when the opponent is
 * identifiable — but the backend doesn't foreign-key the opponent at all (most
 * opponents aren't on the coach's roster), so `opponentId` is often a per-match
 * stand-in id instead, generated by `createMatch`, not a real `Player` row. When
 * that's the case `opponentName` carries the free text the backend actually stores
 * (`Match.opponent_name`) — see `point.ts` and
 * `apps/api/src/matchpoint_api/models/match.py`.
 */
export class Match {
  readonly matchId: string;
  // ISO 8601 date only (YYYY-MM-DD) — matches the backend's `played_on`
  // column exactly (see apps/api/src/matchpoint_api/schemas/match.py), which
  // has no time component. No time-of-day is captured here on purpose.
  readonly playedOn: string;
  readonly trackedPlayerId: string;
  readonly opponentId: string;
  // Null when the opponent is a real, rostered Player — their name lives on
  // that Player row. Set when opponentId is a stand-in id instead, matching
  // the backend's free-text opponent_name (see the class doc comment above).
  readonly opponentName: string | null;
  readonly scoringSystem: ScoringSystem;
  // Must equal trackedPlayerId or opponentId — checked in Match.create, same
  // as Point.server (see point.ts). Not a "player" | "opponent" role label:
  // one representation for "which of the two people" throughout the model.
  // Its *purpose* still differs from Point.server, though — this is a seed
  // for the match's serve-alternation pattern (who serves game N follows
  // from this plus standard tennis rules), not a recorded fact about one
  // already-played point. Reading this alone tells you who started the
  // pattern, not who's serving right now.
  readonly firstServer: string;
  readonly surfaceType: SurfaceType;
  // Null for a normally-completed (or still in-progress) match. Set when
  // the match ended other than by winning enough sets (see
  // MatchOutcomeOverride above). Whoever determines a match's final
  // outcome must check this first and only fall back to matchStateFor's
  // set-count derivation when it's null — this isn't reconciled with that
  // derivation automatically, since Match has no visibility into its own
  // MatchSets to reconcile against (see match-set.ts).
  readonly outcomeOverride: MatchOutcomeOverride | null;

  private constructor(fields: {
    matchId: string;
    playedOn: string;
    trackedPlayerId: string;
    opponentId: string;
    opponentName: string | null;
    scoringSystem: ScoringSystem;
    firstServer: string;
    surfaceType: SurfaceType;
    outcomeOverride: MatchOutcomeOverride | null;
  }) {
    this.matchId = fields.matchId;
    this.playedOn = fields.playedOn;
    this.trackedPlayerId = fields.trackedPlayerId;
    this.opponentId = fields.opponentId;
    this.opponentName = fields.opponentName;
    this.scoringSystem = fields.scoringSystem;
    this.firstServer = fields.firstServer;
    this.surfaceType = fields.surfaceType;
    this.outcomeOverride = fields.outcomeOverride;
  }

  // TODO: rough first pass at structural checks, matching Point.create's approach —
  // revisit once the outbox/sync layer settles on how untrusted this input really is.
  static create(input: unknown): Match {
    if (typeof input !== "object" || input === null) {
      throw new Error("match data must be an object");
    }
    const data = input as Record<string, unknown>;

    if (typeof data.matchId !== "string" || data.matchId.length === 0) {
      throw new Error("match id must be a non-empty string");
    }
    // Date-only (YYYY-MM-DD), not a datetime: matches the backend's `played_on`
    // column, which has no time component (see the field comment above). The
    // regex first, not just Date.parse, because Date.parse alone accepts far
    // more than the backend does — a full datetime string would parse fine
    // here and then fail against the backend later, exactly the mismatch
    // this field exists to avoid. Future-date/lookback bounds are deliberately
    // not re-checked here — those are business rules for the match setup form
    // and the backend, not structural validation (see PlayedOn in
    // apps/api/src/matchpoint_api/schemas/match.py).
    if (
      typeof data.playedOn !== "string" ||
      !/^\d{4}-\d{2}-\d{2}$/.test(data.playedOn) ||
      Number.isNaN(Date.parse(data.playedOn))
    ) {
      throw new Error("match playedOn must be a valid date string (YYYY-MM-DD)");
    }
    if (typeof data.trackedPlayerId !== "string" || data.trackedPlayerId.length === 0) {
      throw new Error("trackedPlayerId must be a non-empty string");
    }
    if (typeof data.opponentId !== "string" || data.opponentId.length === 0) {
      throw new Error("opponentId must be a non-empty string");
    }
    if (data.trackedPlayerId === data.opponentId) {
      throw new Error("trackedPlayerId and opponentId must be different");
    }
    if (
      data.opponentName !== null &&
      (typeof data.opponentName !== "string" || data.opponentName.length === 0)
    ) {
      throw new Error("opponentName must be a non-empty string, or null");
    }
    if (!SCORING_SYSTEMS.includes(data.scoringSystem as ScoringSystem)) {
      throw new Error(`invalid scoringSystem: ${String(data.scoringSystem)}`);
    }
    // Same check as Point.create runs on server: must be trackedPlayerId or
    // opponentId, not a "player" | "opponent" role label — see the field
    // comment above.
    if (![data.trackedPlayerId, data.opponentId].includes(data.firstServer as string)) {
      throw new Error(
        `firstServer must be trackedPlayerId or opponentId, got: ${String(data.firstServer)}`,
      );
    }
    if (!SURFACE_TYPES.includes(data.surfaceType as SurfaceType)) {
      throw new Error(`invalid surfaceType: ${String(data.surfaceType)}`);
    }

    let outcomeOverride: MatchOutcomeOverride | null = null;
    if (data.outcomeOverride !== null) {
      if (typeof data.outcomeOverride !== "object") {
        throw new Error("outcomeOverride must be an object, or null");
      }
      const overrideData = data.outcomeOverride as Record<string, unknown>;
      if (!MATCH_END_REASONS.includes(overrideData.reason as MatchEndReason)) {
        throw new Error(`invalid outcomeOverride.reason: ${String(overrideData.reason)}`);
      }
      if (![data.trackedPlayerId, data.opponentId].includes(overrideData.winner as string)) {
        throw new Error(
          `outcomeOverride.winner must be trackedPlayerId or opponentId, got: ${String(overrideData.winner)}`,
        );
      }
      outcomeOverride = {
        reason: overrideData.reason as MatchEndReason,
        winner: overrideData.winner as string,
      };
    }

    return new Match({
      matchId: data.matchId,
      playedOn: data.playedOn,
      trackedPlayerId: data.trackedPlayerId,
      opponentId: data.opponentId,
      opponentName: data.opponentName as string | null,
      scoringSystem: data.scoringSystem as ScoringSystem,
      firstServer: data.firstServer as string,
      surfaceType: data.surfaceType as SurfaceType,
      outcomeOverride,
    });
  }

  static fromJSON(json: unknown): Match {
    return Match.create(json);
  }

  toJSON() {
    return {
      matchId: this.matchId,
      playedOn: this.playedOn,
      trackedPlayerId: this.trackedPlayerId,
      opponentId: this.opponentId,
      opponentName: this.opponentName,
      scoringSystem: this.scoringSystem,
      firstServer: this.firstServer,
      surfaceType: this.surfaceType,
      outcomeOverride: this.outcomeOverride,
    };
  }
}

/**
 * Creates a new Match, generating a fresh matchId. Field validation
 * (non-empty ids, valid enum members, etc.) happens in `Match.create`, same
 * as for any other caller.
 *
 * `opponent` takes exactly one of two shapes — the opponent is a real,
 * rostered Player (`opponentId`), or they aren't (`opponentName`), the more
 * common case per the backend (see the class doc comment above). In the
 * latter case this generates the per-match stand-in id point.ts's contract
 * assumes Match provides, so every Point still gets two real ids to compare
 * `winner`/`server` against — nothing else has to invent one.
 *
 * `scoringSystem`/`surfaceType` default rather than being required — a coach
 * shouldn't be blocked setting up a match because they haven't picked a
 * scoring format or don't know the surface. `"traditional"` is the
 * assumed-common format; `"unspecified"` is a real SurfaceType value, not a
 * missing one (see its definition above). Once coach preferences exist,
 * that's the natural place to pass a saved default in instead of relying on
 * these — these defaults just mean setup works without that existing yet.
 *
 * `outcomeOverride` defaults to null — a newly-started match hasn't ended.
 * It exists as a parameter here (rather than only settable later) for a
 * back-filled match, entered after the fact already known to have ended
 * in a retirement, walkover, or default — same reasoning as the backend's
 * own `result` field being settable on create (see
 * apps/api/src/matchpoint_api/models/match.py).
 */
export function createMatch(
  playedOn: string,
  trackedPlayerId: string,
  opponent: { opponentId: string } | { opponentName: string },
  firstServer: string,
  scoringSystem: ScoringSystem = "traditional",
  surfaceType: SurfaceType = "unspecified",
  outcomeOverride: MatchOutcomeOverride | null = null,
): Match {
  const opponentId = "opponentId" in opponent ? opponent.opponentId : crypto.randomUUID();
  const opponentName = "opponentId" in opponent ? null : opponent.opponentName;

  return Match.create({
    matchId: crypto.randomUUID(),
    playedOn,
    trackedPlayerId,
    opponentId,
    opponentName,
    scoringSystem,
    firstServer,
    surfaceType,
    outcomeOverride,
  });
}
